/** Generic "insert one new session row" — replaces the old localStorage
 *  `persistSessions(fullArray)` pattern (Supabase has no cheap "replace the
 *  whole table" primitive). Optimistic: returns a client-side session
 *  immediately (temp id), the real insert + id swap happen in the
 *  background. */
function createSessionInternal(input: Partial<ExtSession> & {
  student_id: string;
  teacher_id: string;
  date_time: string;
  duration_minutes: number;
  teams_link: string;
}): ExtSession {
  const tempId = `temp-${Date.now()}-${Math.random().toString(36).slice(2, 8)}`;
  const optimistic: ExtSession = {
    status: "scheduled",
    ...input,
    id: tempId,
  };
  sessionsCache = [optimistic, ...sessionsCache];
  notify();

  void (async () => {
    const [studentUuid, teacherUuid] = await Promise.all([
      input.student_id ? legacyToUuid(input.student_id) : Promise.resolve(null),
      legacyToUuid(input.teacher_id),
    ]);
    if (!teacherUuid) {
      console.error("[sessions-store] unknown teacher id, dropping optimistic session", input.teacher_id);
      sessionsCache = sessionsCache.filter((s) => s.id !== tempId);
      notify();
      return;
    }
    const insert: SessionInsert = {
      student_id: studentUuid,
      teacher_id: teacherUuid,
      date_time: input.date_time,
      duration_minutes: input.duration_minutes,
      teams_link: input.teams_link,
      status: input.status ?? "scheduled",
      origin: input.origin,
      notes: input.notes ?? null,
      group_id: input.group_id ? Number(input.group_id) : null,
      workshop_cohort_id: input.workshop_cohort_id ? Number(input.workshop_cohort_id) : null,
      workshop_template_id: input.workshop_template_id ? Number(input.workshop_template_id) : null,
      workshop_topic: input.workshop_topic ?? null,
    };
    const { data, error } = await supabase.from("sessions").insert(insert).select("*").single();
    if (error || !data) {
      console.error("[sessions-store] failed to create session", error);
      sessionsCache = sessionsCache.filter((s) => s.id !== tempId);
      notify();
      return;
    }
    const created = mapSessionRow(data, [], []);
    sessionsCache = sessionsCache.map((s) => (s.id === tempId ? created : s));
    notify();
  })();

  return optimistic;
}

/** Public wrapper around `createSessionInternal` — the replacement for the
 *  old localStorage-era `persistSessions(fullArray)` escape hatch. Any
 *  caller (e.g. student-requests-store's claim/spotlight-conversion flows)
 *  that needs to materialize a brand-new session should use this instead of
 *  reaching into the cache directly. */
export function createSession(input: Partial<ExtSession> & {
  student_id: string;
  teacher_id: string;
  date_time: string;
  duration_minutes: number;
  teams_link: string;
}): ExtSession {
  return createSessionInternal(input);
}

