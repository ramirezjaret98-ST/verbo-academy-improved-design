export type ExtSessionStatus =
  | "scheduled"
  | "rescheduled"
  | "ready"
  | "rearranged"
  | "completed"
  | "absent"
  | "delayed"
  | "cancelled"
  | "pending_reschedule"
  | "no_show"
  // Student replaced this 1:1 with a Spotlight in the same slot. Not a strike,
  // not Cancelled, not Absent — its own status with its own indigo color.
  | "converted_to_spotlight";

// Optional refinement of an Absent or Cancelled status. All six sub-statuses
// count the session as accounted for but do NOT penalize attendance metrics
// (that's the whole point of a justification). They live alongside `status`
// so existing consumers keep working, and so a session can be Absent while
// still carrying "Absent Illness" context.
export type AttendanceSubStatus =
  | "absent_work"
  | "absent_illness"
  | "absent_vacation"
  | "cancelled_illness"
  | "cancelled_holiday"
  | "cancelled_work";

export interface ReportAdminEdit {
  at: string;
  actorId: string;
  actorName?: string;
  studentId?: string;
  field: "status" | "sub_status" | "member_status" | "member_sub_status";
  from: string;
  to: string;
  note?: string;
}

export interface ExtSession {
  id: string;
  student_id: string;
  teacher_id: string;
  date_time: string; // ISO
  duration_minutes: number;
  teams_link: string;
  status: ExtSessionStatus;
  absent_cause?: "student" | "teacher";
  report_pdf_url?: string;
  student_rating?: number;
  student_comment?: string;
  review_status?: "pending" | "reviewed" | "discarded";
  review_note?: string;
  notes?: string;
  attendance_delayed?: boolean;
  report_submitted_at?: string;
  origin?: "course" | "workshop" | "spotlight" | "group";
  workshop_cohort_id?: string;
  workshop_template_id?: string;
  workshop_topic?: string;
  group_id?: string;
  member_statuses?: Record<string, ExtSessionStatus>;
  member_absent_cause?: Record<string, "student" | "teacher">;
  /** Sub-status for the top-level Absent/Cancelled status (1:1 sessions). */
  attendance_sub_status?: AttendanceSubStatus;
  /** Per-member sub-status (group sessions). */
  member_sub_statuses?: Record<string, AttendanceSubStatus>;
  /** True once submitSessionReport / submitGroupSessionReport has run.
   *  Locks the teacher out of editing statuses; Admin can still amend. */
  report_locked?: boolean;
  /** Ordered audit trail of Admin edits after `report_locked` was set. */
  report_admin_edits?: ReportAdminEdit[];
  cancellation_reason?: "illness" | "personal" | "major_issue" | "other";
  cancellation_note?: string;
  needs_substitute?: boolean;
  /** True once a substitute teacher has been assigned to cover this session. */
  covered_by_substitute?: boolean;
  report_comments?: string;
  /** True only for sessions auto-generated by the Bulk Scheduler as a
   *  replacement for a date that landed on an official holiday. */
  holiday_makeup?: boolean;
}

export const SESSIONS_EVENT = "verbo:sessions-updated";

type SessionRow = Database["public"]["Tables"]["sessions"]["Row"];
type SessionInsert = Database["public"]["Tables"]["sessions"]["Insert"];
type SessionUpdate = Database["public"]["Tables"]["sessions"]["Update"];
type MemberStatusRow = Database["public"]["Tables"]["session_member_statuses"]["Row"];
type AdminEditRow = Database["public"]["Tables"]["report_admin_edits"]["Row"];

let sessionsCache: ExtSession[] = [];
let hydrated = false;
let hydratePromise: Promise<void> | null = null;
const listeners = new Set<() => void>();
const SSR_SNAPSHOT: ExtSession[] = [];

function notify() {
  listeners.forEach((cb) => cb());
  if (typeof window !== "undefined") window.dispatchEvent(new CustomEvent(SESSIONS_EVENT));
}

function setSessionEntry(id: string, session: ExtSession | undefined, prepend?: ExtSession) {
  if (prepend) {
    sessionsCache = [prepend, ...sessionsCache];
    return;
  }
  if (session) {
    sessionsCache = sessionsCache.map((s) => (s.id === id ? session : s));
  } else {
    sessionsCache = sessionsCache.filter((s) => s.id !== id);
  }
}

function mapSessionRow(row: SessionRow, members: MemberStatusRow[], edits: AdminEditRow[]): ExtSession {
  const memberStatuses: Record<string, ExtSessionStatus> = {};
  const memberAbsentCause: Record<string, "student" | "teacher"> = {};
  const memberSubStatuses: Record<string, AttendanceSubStatus> = {};
  for (const m of members) {
    const legacyId = uuidToLegacySync(m.student_id);
    memberStatuses[legacyId] = m.status;
    if (m.absent_cause === "student" || m.absent_cause === "teacher") memberAbsentCause[legacyId] = m.absent_cause;
    if (m.attendance_sub_status) memberSubStatuses[legacyId] = m.attendance_sub_status;
  }
  const reportAdminEdits: ReportAdminEdit[] = edits
    .slice()
    .sort((a, b) => +new Date(a.at) - +new Date(b.at))
    .map((e) => ({
      at: e.at,
      actorId: uuidToLegacySync(e.actor_id),
      actorName: e.actor_name ?? undefined,
      studentId: e.student_id ? uuidToLegacySync(e.student_id) : undefined,
      field: e.field as ReportAdminEdit["field"],
      from: e.from_value,
      to: e.to_value,
      note: e.note ?? undefined,
    }));

  return {
    id: String(row.id),
    student_id: row.student_id ? uuidToLegacySync(row.student_id) : "",
    teacher_id: uuidToLegacySync(row.teacher_id),
    date_time: row.date_time,
    duration_minutes: row.duration_minutes,
    teams_link: row.teams_link,
    status: row.status,
    absent_cause: (row.absent_cause as "student" | "teacher" | null) ?? undefined,
    report_pdf_url: row.report_pdf_url ?? undefined,
    student_rating: row.student_rating ?? undefined,
    student_comment: row.student_comment ?? undefined,
    review_status: (row.review_status as ExtSession["review_status"]) ?? undefined,
    review_note: row.review_note ?? undefined,
    notes: row.notes ?? undefined,
    attendance_delayed: row.attendance_delayed ?? undefined,
    report_submitted_at: row.report_submitted_at ?? undefined,
    origin: row.origin ?? undefined,
    workshop_cohort_id: row.workshop_cohort_id !== null ? String(row.workshop_cohort_id) : undefined,
    workshop_template_id: row.workshop_template_id !== null ? String(row.workshop_template_id) : undefined,
    workshop_topic: row.workshop_topic ?? undefined,
    group_id: row.group_id !== null ? String(row.group_id) : undefined,
    attendance_sub_status: row.attendance_sub_status ?? undefined,
    report_locked: row.report_locked ?? undefined,
    cancellation_reason: row.cancellation_reason ?? undefined,
    cancellation_note: row.cancellation_note ?? undefined,
    needs_substitute: row.needs_substitute ?? undefined,
    covered_by_substitute: row.covered_by_substitute ?? undefined,
    report_comments: row.report_comments ?? undefined,
    holiday_makeup: row.holiday_makeup ?? undefined,
    member_statuses: Object.keys(memberStatuses).length ? memberStatuses : undefined,
    member_absent_cause: Object.keys(memberAbsentCause).length ? memberAbsentCause : undefined,
    member_sub_statuses: Object.keys(memberSubStatuses).length ? memberSubStatuses : undefined,
    report_admin_edits: reportAdminEdits.length ? reportAdminEdits : undefined,
  };
}

async function hydrate(): Promise<void> {
  if (hydrated) return;
  if (hydratePromise) return hydratePromise;
  hydratePromise = (async () => {
    await hydrateUserIdBridge();
    const [sessionsRes, membersRes, editsRes] = await Promise.all([
      supabase.from("sessions").select("*"),
      supabase.from("session_member_statuses").select("*"),
      supabase.from("report_admin_edits").select("*"),
    ]);
    if (sessionsRes.error) console.error("[sessions-store] failed to load sessions", sessionsRes.error);
    if (membersRes.error) console.error("[sessions-store] failed to load session_member_statuses", membersRes.error);
    if (editsRes.error) console.error("[sessions-store] failed to load report_admin_edits", editsRes.error);

    const membersBySession = new Map<number, MemberStatusRow[]>();
    for (const m of (membersRes.data ?? []) as MemberStatusRow[]) {
      const list = membersBySession.get(m.session_id) ?? [];
      list.push(m);
      membersBySession.set(m.session_id, list);
    }
    const editsBySession = new Map<number, AdminEditRow[]>();
    for (const e of (editsRes.data ?? []) as AdminEditRow[]) {
      const list = editsBySession.get(e.session_id) ?? [];
      list.push(e);
      editsBySession.set(e.session_id, list);
    }

    sessionsCache = ((sessionsRes.data ?? []) as SessionRow[]).map((row) =>
      mapSessionRow(row, membersBySession.get(row.id) ?? [], editsBySession.get(row.id) ?? []),
    );
    hydrated = true;
  })();
  await hydratePromise;
  hydratePromise = null;
  notify();
}

function invalidateAndRehydrate() {
  hydrated = false;
  hydratePromise = null;
  void hydrate();
}

