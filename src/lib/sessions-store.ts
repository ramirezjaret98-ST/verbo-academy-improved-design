// ---------------------------------------------------------------------------
// Attendance — single shared source of truth for the "% of sessions attended"
// metric.
// ---------------------------------------------------------------------------
export interface StudentAttendanceSummary {
  completed: number;
  absent: number;
  pct: number;
}

export const ATTENDANCE_WINDOW_DAYS = 90;

export function studentAttendance(
  sessions: Array<{ student_id: string; status: string; date_time?: string }>,
  student: { id: string; attendance_percentage?: number },
): StudentAttendanceSummary {
  const cutoff = Date.now() - ATTENDANCE_WINDOW_DAYS * 86_400_000;
  const rows = sessions.filter((s) => {
    if (s.student_id !== student.id) return false;
    const t = s.date_time ? new Date(s.date_time).getTime() : NaN;
    return Number.isFinite(t) ? t >= cutoff && t <= Date.now() : false;
  });
  const completed = rows.filter((s) => s.status === "completed").length;
  const absent = rows.filter((s) => s.status === "absent").length;
  const total = completed + absent;
  const pct = student.attendance_percentage ?? (total > 0 ? Math.round((completed / total) * 100) : 0);
  return { completed, absent, pct };
}

// ---------------------------------------------------------------------------
// Latest teacher report snippet for a student.
// ---------------------------------------------------------------------------
export function lastCoveredSummaryFor(
  sessions: Array<{ student_id: string; status: string; date_time: string; report_comments?: string }>,
  studentId: string,
): string | undefined {
  const rows = sessions
    .filter((s) => s.student_id === studentId && s.status === "completed" && s.report_comments?.trim())
    .sort((a, b) => +new Date(b.date_time) - +new Date(a.date_time));
  const text = rows[0]?.report_comments?.trim();
  if (!text) return undefined;
  return text.length > 140 ? text.slice(0, 140).trim() + "…" : text;
}
