export function removeWorkshopSession(id: string) {
  const prev = sessionsCache;
  sessionsCache = sessionsCache.filter((s) => s.id !== id);
  notify();
  const numericId = Number(id);
  if (!Number.isFinite(numericId)) return;
  void (async () => {
    const { error } = await supabase.from("sessions").delete().eq("id", numericId);
    if (error) {
      console.error("[sessions-store] failed to remove workshop session", error);
      sessionsCache = prev;
      notify();
    }
  })();
}

/** Background helper backing the multi-row RPC. Not exported — internal
 *  writes route through here; callers get the optimistic cache update
 *  synchronously via their own function, this just fires the real DB call. */
async function upsertMemberStatuses(input: {
  sessionId: string;
  setTopStatus?: ExtSessionStatus;
  setReportLocked?: boolean;
  reportSubmittedAt?: string;
  members: Array<{ studentId: string; status: ExtSessionStatus; absentCause?: "student" | "teacher"; subStatus?: AttendanceSubStatus | null }>;
}): Promise<boolean> {
  const numericId = Number(input.sessionId);
  if (!Number.isFinite(numericId)) return false;
  const membersPayload = await Promise.all(
    input.members.map(async (m) => ({
      studentId: await legacyToUuid(m.studentId),
      status: m.status,
      absentCause: m.absentCause ?? "",
      subStatus: m.subStatus ?? "",
    })),
  );
  if (membersPayload.some((m) => !m.studentId)) {
    console.error("[sessions-store] unknown student id in member_statuses payload");
    return false;
  }
  const { error } = await supabase.rpc("upsert_session_member_statuses", {
    p_session_id: numericId,
    p_set_top_status: input.setTopStatus !== undefined,
    p_top_status: input.setTopStatus ?? "scheduled",
    p_set_report_locked: input.setReportLocked !== undefined,
    p_report_locked: input.setReportLocked ?? false,
    // Runtime-nullable (the SQL function does `if ... or p_report_submitted_at
    // is not null` and only touches the column when it's actually provided),
    // but Supabase's codegen can't see that from a plain `timestamptz` param
    // and generates a non-null Args type — hence the cast.
    p_report_submitted_at: (input.reportSubmittedAt ?? null) as unknown as string,
    p_members: membersPayload,
  });
  if (error) {
    console.error("[sessions-store] upsert_session_member_statuses failed", error);
    return false;
  }
  return true;
}

/** Generic patcher — used by Lesson Plan (→ Ready) and by any other
 *  surface that needs to update a single session while keeping every
 *  consumer live-synced. A `member_statuses` key in the patch is treated as
 *  the FULL desired per-member map (matching the caller convention already
 *  in place, e.g. CancelSessionFlow spreads the previous map + one changed
 *  key) — every entry present gets upserted into `session_member_statuses`
 *  via the atomic RPC; entries removed from the map are NOT deleted (no
 *  caller relies on removal, only on adding/changing one member at a time). */
export function updateSession(id: string, patch: Partial<ExtSession>) {
  const prev = sessionsCache.find((s) => s.id === id);
  if (!prev) return;
  const next: ExtSession = { ...prev, ...patch };
  sessionsCache = sessionsCache.map((s) => (s.id === id ? next : s));
  notify();

  const numericId = Number(id);
  if (!Number.isFinite(numericId)) return;

  if (patch.member_statuses) {
    const members = Object.entries(patch.member_statuses).map(([studentId, status]) => ({
      studentId,
      status,
      absentCause: patch.member_absent_cause?.[studentId],
      subStatus: patch.member_sub_statuses?.[studentId],
    }));
    void upsertMemberStatuses({ sessionId: id, members }).then((ok) => {
      if (!ok) {
        sessionsCache = sessionsCache.map((s) => (s.id === id ? prev : s));
        notify();
      }
    });
    // member_statuses can arrive alongside a top-level status change too
    // (rare, but keep both effects consistent) — fall through to the plain
    // update below for every OTHER field in the patch.
  }

  const update: SessionUpdate = {};
  if (patch.status !== undefined) update.status = patch.status;
  if (patch.date_time !== undefined) update.date_time = patch.date_time;
  if (patch.duration_minutes !== undefined) update.duration_minutes = patch.duration_minutes;
  if (patch.teams_link !== undefined) update.teams_link = patch.teams_link;
  if (patch.notes !== undefined) update.notes = patch.notes ?? null;
  if (patch.absent_cause !== undefined) update.absent_cause = patch.absent_cause ?? null;
  if (patch.report_pdf_url !== undefined) update.report_pdf_url = patch.report_pdf_url ?? null;
  if (patch.student_rating !== undefined) update.student_rating = patch.student_rating ?? null;
  if (patch.student_comment !== undefined) update.student_comment = patch.student_comment ?? null;
  if (patch.review_status !== undefined) update.review_status = patch.review_status ?? null;
  if (patch.review_note !== undefined) update.review_note = patch.review_note ?? null;
  if (patch.attendance_delayed !== undefined) update.attendance_delayed = patch.attendance_delayed ?? null;
  if (patch.report_submitted_at !== undefined) update.report_submitted_at = patch.report_submitted_at ?? null;
  if (patch.attendance_sub_status !== undefined) update.attendance_sub_status = patch.attendance_sub_status ?? null;
  if (patch.report_locked !== undefined) update.report_locked = patch.report_locked ?? null;
  if (patch.cancellation_reason !== undefined) update.cancellation_reason = patch.cancellation_reason ?? null;
  if (patch.cancellation_note !== undefined) update.cancellation_note = patch.cancellation_note ?? null;
  if (patch.needs_substitute !== undefined) update.needs_substitute = patch.needs_substitute ?? null;
  if (patch.covered_by_substitute !== undefined) update.covered_by_substitute = patch.covered_by_substitute ?? null;
  if (patch.report_comments !== undefined) update.report_comments = patch.report_comments ?? null;
  if (patch.holiday_makeup !== undefined) update.holiday_makeup = patch.holiday_makeup ?? null;
  if (patch.workshop_topic !== undefined) update.workshop_topic = patch.workshop_topic ?? null;
  if ("teacher_id" in patch && patch.teacher_id) {
    void (async () => {
      const teacherUuid = await legacyToUuid(patch.teacher_id!);
      if (!teacherUuid) return;
      const { error } = await supabase.from("sessions").update({ teacher_id: teacherUuid }).eq("id", numericId);
      if (error) console.error("[sessions-store] failed to update teacher_id", error);
    })();
  }

  if (Object.keys(update).length === 0) return;
  void (async () => {
    const { error } = await supabase.from("sessions").update(update).eq("id", numericId);
    if (error) {
      console.error("[sessions-store] failed to update session", error);
      sessionsCache = sessionsCache.map((s) => (s.id === id ? prev : s));
      notify();
    }
  })();
}

/** Persist a student's rating for a completed session. Ratings of 3★ or
 *  below flip `review_status` to "pending" so the session enters the
 *  Flagged Reviews queue in Admin > Teachers. Higher ratings leave
 *  `review_status` untouched. */
export function submitStudentRating(sessionId: string, rating: number, comment?: string) {
  const patch: Partial<ExtSession> = { student_rating: rating };
  if (comment !== undefined) patch.student_comment = comment;
  if (rating <= 3) patch.review_status = "pending";
  updateSession(sessionId, patch);
}

/** Final Session Report submit. Single source of truth for the four
 *  effects the spec requires:
 *    1. Session → Completed (Present/Delayed) or Absent (with cause).
 *    2. Attendance metadata (delayed flag).
 *    3. Real per-subskill scores flow into the same performance store
 *       the student dashboard + Teacher > Mis Alumnos read from.
 *    4. Any coverage note for (teacher, student) is cleared.
 *
 *  Not handled here on purpose: PDF generation and email dispatch.
 */
export function submitSessionReport(input: {
  sessionId: string;
  teacherId: string;
  studentId: string;
  attendance: "present" | "delayed" | "absent";
  absentCause?: "student" | "teacher";
  subStatus?: AttendanceSubStatus | null;
  subskills: Record<string, number>;
  reportComments?: string;
  /** Required "Class notes" write-up from the report form. Previously this
   *  was only ever baked into the generated PDF and never persisted to a
   *  queryable column — Admin had no way to see it without opening the PDF.
   *  Now saved to `sessions.notes` alongside everything else. */
  notes?: string;
}): ExtSession | null {
  const prev = sessionsCache.find((s) => s.id === input.sessionId);
  if (!prev) return null;
  const status: ExtSessionStatus = input.attendance === "absent" ? "absent" : "completed";
  const patch: Partial<ExtSession> = {
    status,
    absent_cause: status === "absent" ? (input.absentCause ?? "student") : undefined,
    attendance_delayed: input.attendance === "delayed",
    attendance_sub_status: status === "absent" && input.subStatus ? input.subStatus : undefined,
    report_submitted_at: new Date().toISOString(),
    report_locked: true,
    report_comments: input.reportComments?.trim() ? input.reportComments.trim() : prev.report_comments,
    notes: input.notes?.trim() ? input.notes.trim() : prev.notes,
  };
  updateSession(input.sessionId, patch);

  if (status !== "absent" && Object.keys(input.subskills).length > 0) {
    saveSubskillEvaluation(input.sessionId, input.studentId, input.teacherId, input.subskills);
  }
  setCoverageNote(input.teacherId, input.studentId, "");

  // Decrement remaining_sessions for 1:1 individual sessions when the class
  // actually occurred. Mirrors the group-side rule in submitGroupSessionReport.
  const isOneOnOne = !prev.origin && !prev.group_id && !prev.workshop_cohort_id && !prev.workshop_template_id;
  const classOccurred = !(status === "absent" && input.absentCause === "teacher");
  if (isOneOnOne && classOccurred) {
    adjustRemainingSessions(input.studentId, -1);
  }
  return { ...prev, ...patch };
}

// -----------------------------------------------------------------------------
// Group Session Report — one shared class, per-member attendance & evaluation.
// -----------------------------------------------------------------------------
export function submitGroupSessionReport(input: {
  sessionId: string;
  teacherId: string;
  groupId: string;
  perMember: Array<{
    studentId: string;
    attendance: "present" | "delayed" | "absent";
    absentCause?: "student" | "teacher";
    subStatus?: AttendanceSubStatus | null;
    subskills: Record<string, number>;
  }>;
}): ExtSession | null {
  const prev = sessionsCache.find((s) => s.id === input.sessionId);
  if (!prev) return null;

  const memberStatuses: Record<string, ExtSessionStatus> = { ...(prev.member_statuses ?? {}) };
  const memberAbsentCause: Record<string, "student" | "teacher"> = { ...(prev.member_absent_cause ?? {}) };
  const memberSubStatuses: Record<string, AttendanceSubStatus> = { ...(prev.member_sub_statuses ?? {}) };
  for (const m of input.perMember) {
    memberStatuses[m.studentId] = m.attendance === "absent" ? "absent" : "completed";
    if (m.attendance === "absent") memberAbsentCause[m.studentId] = m.absentCause ?? "student";
    if (m.attendance === "absent" && m.subStatus) memberSubStatuses[m.studentId] = m.subStatus;
  }
  const anyPresent = input.perMember.some((m) => m.attendance !== "absent");
  const nextTop: ExtSessionStatus = anyPresent ? "completed" : "absent";
  const reportSubmittedAt = new Date().toISOString();

  const optimistic: ExtSession = {
    ...prev,
    status: nextTop,
    member_statuses: memberStatuses,
    member_absent_cause: memberAbsentCause,
    member_sub_statuses: memberSubStatuses,
    report_submitted_at: reportSubmittedAt,
    report_locked: true,
  };
  sessionsCache = sessionsCache.map((s) => (s.id === input.sessionId ? optimistic : s));
  notify();

  void upsertMemberStatuses({
    sessionId: input.sessionId,
    setTopStatus: nextTop,
    setReportLocked: true,
    reportSubmittedAt,
    members: input.perMember.map((m) => ({
      studentId: m.studentId,
      status: m.attendance === "absent" ? "absent" : "completed",
      absentCause: m.attendance === "absent" ? (m.absentCause ?? "student") : undefined,
      subStatus: m.attendance === "absent" ? m.subStatus : undefined,
    })),
  }).then((ok) => {
    if (!ok) {
      sessionsCache = sessionsCache.map((s) => (s.id === input.sessionId ? prev : s));
      notify();
    }
  });

  for (const m of input.perMember) {
    if (m.attendance !== "absent" && Object.keys(m.subskills).length > 0) {
      saveSubskillEvaluation(input.sessionId, m.studentId, input.teacherId, m.subskills);
    }
    setCoverageNote(input.teacherId, m.studentId, "");
  }

  // Group progress advances exactly once (not per member), and only when the
  // class actually took place.
  const classOccurred = input.perMember.some(
    (m) => m.attendance !== "absent" || (m.absentCause ?? "student") === "student",
  );
  if (classOccurred) decrementGroupRemaining(input.groupId);

  return optimistic;
}

// -----------------------------------------------------------------------------
// Group Session Unanimity — Can't Attend flow.
// -----------------------------------------------------------------------------
export type GroupUnanimityOutcome =
  | { kind: "none" }
  | { kind: "unanimous_cancel" }
  | { kind: "unanimous_reschedule" };

/** Pure evaluator — returns what the top-level status *should* be given the
 *  current member_statuses map. Does not mutate. See file-header note: for a
 *  non-admin/non-teacher caller, `session.member_statuses` may only contain
 *  their own entry (RLS), so unanimity can under-detect for students today. */
export function evaluateGroupUnanimity(
  session: ExtSession,
  overrideMemberStatuses?: Record<string, ExtSessionStatus>,
): GroupUnanimityOutcome {
  if (!session.group_id) return { kind: "none" };
  const memberStatuses = overrideMemberStatuses ?? session.member_statuses ?? {};
  const rosterIds = activeMembersOf(session.group_id).map((m) => m.student_id);
  if (rosterIds.length === 0) return { kind: "none" };
  const values = rosterIds.map((id) => memberStatuses[id]);
  if (values.every((v) => v === "cancelled")) return { kind: "unanimous_cancel" };
  if (values.every((v) => v === "pending_reschedule")) return { kind: "unanimous_reschedule" };
  return { kind: "none" };
}

/** Applies a per-member cancel or reschedule to a group session and evaluates
 *  strict unanimity. Returns the outcome so the caller can toast / trigger a
 *  group-level Reschedule Request when unanimity flips top-level state. */
export function applyGroupMemberCancellation(
  sessionId: string,
  studentId: string,
  memberStatus: "cancelled" | "pending_reschedule",
): { outcome: GroupUnanimityOutcome; topStatus: ExtSessionStatus } {
  const sess = sessionsCache.find((s) => s.id === sessionId);
  if (!sess || !sess.group_id) {
    updateSession(sessionId, { status: memberStatus });
    return { outcome: { kind: "none" }, topStatus: memberStatus };
  }

  const nextMemberStatuses: Record<string, ExtSessionStatus> = {
    ...(sess.member_statuses ?? {}),
    [studentId]: memberStatus,
  };
  const outcome = evaluateGroupUnanimity(sess, nextMemberStatuses);
  const patch: Partial<ExtSession> = { member_statuses: nextMemberStatuses };
  if (outcome.kind === "unanimous_cancel") patch.status = "cancelled";
  else if (outcome.kind === "unanimous_reschedule") patch.status = "pending_reschedule";
  updateSession(sessionId, patch);
  return {
    outcome,
    topStatus: (patch.status ?? sess.status) as ExtSessionStatus,
  };
}

// -----------------------------------------------------------------------------
// Admin overrides after a Session Report is locked. No current call sites in
// the app (prepared for a future Admin UI) — implemented against the real
// schema (INSERT-only `report_admin_edits`, matching its append-only RLS).
// -----------------------------------------------------------------------------
export function adminAmendSession(
  sessionId: string,
  actor: { id: string; name?: string },
  edit: {
    studentId?: string;
    field: ReportAdminEdit["field"];
    to: string;
    note?: string;
  },
): ExtSession | null {
  const s = sessionsCache.find((x) => x.id === sessionId);
  if (!s) return null;

  let from = "";
  const patch: Partial<ExtSession> = {};
  if (edit.field === "status") {
    from = s.status;
    patch.status = edit.to as ExtSessionStatus;
  } else if (edit.field === "sub_status") {
    from = s.attendance_sub_status ?? "";
    patch.attendance_sub_status = (edit.to || undefined) as AttendanceSubStatus | undefined;
  } else if (edit.field === "member_status" && edit.studentId) {
    from = s.member_statuses?.[edit.studentId] ?? "";
    patch.member_statuses = { ...(s.member_statuses ?? {}), [edit.studentId]: edit.to as ExtSessionStatus };
  } else if (edit.field === "member_sub_status" && edit.studentId) {
    from = s.member_sub_statuses?.[edit.studentId] ?? "";
    const map = { ...(s.member_sub_statuses ?? {}) };
    if (edit.to) map[edit.studentId] = edit.to as AttendanceSubStatus;
    else delete map[edit.studentId];
    patch.member_sub_statuses = map;
  } else {
    return s;
  }

  const auditEntry: ReportAdminEdit = {
    at: new Date().toISOString(),
    actorId: actor.id,
    actorName: actor.name,
    studentId: edit.studentId,
    field: edit.field,
    from,
    to: edit.to,
    note: edit.note,
  };
  const optimistic: ExtSession = {
    ...s,
    ...patch,
    report_admin_edits: [...(s.report_admin_edits ?? []), auditEntry],
  };
  sessionsCache = sessionsCache.map((x) => (x.id === sessionId ? optimistic : x));
  notify();

  updateSession(sessionId, patch);

  const numericId = Number(sessionId);
  if (Number.isFinite(numericId)) {
    void (async () => {
      const actorUuid = await legacyToUuid(actor.id);
      const studentUuid = edit.studentId ? await legacyToUuid(edit.studentId) : null;
      if (!actorUuid) return;
      const { error } = await supabase.from("report_admin_edits").insert({
        session_id: numericId,
        actor_id: actorUuid,
        actor_name: actor.name ?? null,
        student_id: studentUuid,
        field: edit.field,
        from_value: from,
        to_value: edit.to,
        note: edit.note ?? null,
      });
      if (error) console.error("[sessions-store] failed to record admin edit", error);
    })();
  }

  return optimistic;
}

